# install-steamcmd.sh — install Valve's SteamCMD so it runs on any
# architecture i386-compat.sh supports. Run i386-compat.sh install first (it
# provides run-i386) with curl among the extra packages.
#
#   install-steamcmd.sh [--bootstrap] [DIR]
#
# Installs SteamCMD into DIR (default /opt/steamcmd) and writes
# /usr/local/bin/steamcmd, which runs DIR/steamcmd.sh with:
#
#   DEBUGGER=run-i386       steamcmd.sh starts its binary as
#                           `$DEBUGGER linux32/steamcmd ...`, so the 32-bit
#                           SteamCMD runs under qemu-i386 on arm64 and as a
#                           plain exec on x86.
#   STEAM_PLATFORM=linux32  without it steamcmd.sh picks a linuxarm64 build
#                           on arm64, which Valve doesn't ship.
#
# SteamCMD itself is always a 32-bit binary, even when the server it
# downloads is 64-bit, so this is what lets any SteamCMD-installed server be
# fetched from an arm64 image.
#
# --bootstrap runs `steamcmd +quit` once so SteamCMD's self-update (a few
# hundred MB of downloads and unpacking) lands in the image layer instead of
# on every container start.
set -euo pipefail

URL="${STEAMCMD_URL:-https://steamcdn-a.akamaihd.net/client/installer/steamcmd_linux.tar.gz}"
bootstrap=0
if [[ "${1:-}" == "--bootstrap" ]]; then
    bootstrap=1
    shift
fi
DIR="${1:-/opt/steamcmd}"

die() {
    echo "install-steamcmd.sh: $*" >&2
    exit 1
}
command -v run-i386 >/dev/null || die "run-i386 missing: run i386-compat.sh install first"
command -v curl >/dev/null || die "curl missing: pass it to i386-compat.sh install"

mkdir -p "${DIR}"
curl -fsSL "${URL}" | tar -xz -C "${DIR}"
printf '%s\n' \
    '#!/bin/sh' \
    '# Generated by install-steamcmd.sh: SteamCMD via run-i386 (qemu-i386 on arm64).' \
    "export DEBUGGER=\"\${DEBUGGER:-run-i386}\" STEAM_PLATFORM=\"\${STEAM_PLATFORM:-linux32}\"" \
    "exec ${DIR}/steamcmd.sh \"\$@\"" \
    > /usr/local/bin/steamcmd
chmod 0755 /usr/local/bin/steamcmd

if [[ "${bootstrap}" == "1" ]]; then
    # The first run self-updates and may exit non-zero after updating;
    # a second run must succeed.
    steamcmd +quit || steamcmd +quit
fi
