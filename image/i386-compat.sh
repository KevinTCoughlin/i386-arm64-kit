# i386-compat.sh — give a Debian-based image a working 32-bit x86 (i386)
# userland on any architecture, so the same Containerfile builds for amd64 and
# for arm64 (Apple silicon, where Rosetta for Linux only runs x86_64).
#
#   i386-compat.sh install [options] [--] [extra-pkg...]
#       apt-get update, then install the extra (native) packages, the base
#       i386 runtime libraries and any --i386-pkg libraries, plus:
#         /usr/local/bin/run-i386   run an i386 program (always installed)
#         /usr/local/bin/NAME       one per --launcher
#       On architectures that can't execute i386 natively it also installs a
#       static qemu-i386 and the Steam compatibility shim.
#
#       --i386-pkg PKG        extra i386 library package (installed as
#                             PKG:i386, or PKG on an i386 image). Repeatable;
#                             $I386_EXTRA_PACKAGES (space-separated) adds more.
#       --launcher NAME=PATH  install /usr/local/bin/NAME, which runs the i386
#                             binary PATH (it need not exist yet). Repeatable.
#       --keep-apt-lists      don't delete /var/lib/apt/lists afterwards.
#
#   i386-compat.sh packages   print the i386 library packages for this arch
#   i386-compat.sh emulated   exit 0 if this arch runs i386 under qemu
#
# run-i386 PROG [ARGS...]
#   amd64/i386: `exec "$@"` — nothing changes on x86.
#   elsewhere:  qemu-i386 with the shim preloaded and a fake x86
#               /proc/cpuinfo (see i386-qemu-shim.c). PROG is looked up in
#               PATH. PROG must be an ELF binary, not a shell script.
#
# Launchers (--launcher NAME=PATH):
#   amd64/i386: /usr/local/bin/NAME is `exec PATH "$@"`.
#   elsewhere:  /usr/local/bin/NAME execs qemu-i386 through a symlink named
#               NAME (/usr/local/libexec/i386-kit/emu/NAME), so the emulated
#               process's /proc/*/comm, pgrep and pidof show NAME, not
#               "qemu-i386". Use NAME = basename of PATH and health checks
#               such as `pgrep -x NAME` work on every architecture.
#
# Requires Debian (tested: trixie). Ubuntu arm64 keeps i386 packages on a
# different mirror than ports.ubuntu.com and needs extra apt sources.
set -euo pipefail

KIT_DIR=/usr/local/libexec/i386-kit
QEMU=/usr/local/bin/qemu-i386
SHIM=/usr/local/lib/i386-qemu-shim.so
FAKE_CPUINFO=/usr/local/share/i386-kit/cpuinfo
BIN_DIR=/usr/local/bin
SCRIPT_DIR=$(cd "${BASH_SOURCE[0]%/*}" && pwd)
SHIM_SRC="${I386_SHIM_SRC:-${SCRIPT_DIR}/i386-qemu-shim.c}"
ARCH=$(dpkg --print-architecture)

# Base i386 runtime: enough for Valve's SteamCMD/HLDS/srcds and most other
# 32-bit game servers. Add the rest with --i386-pkg.
BASE_LIBS=(libc6 libgcc-s1 libstdc++6 zlib1g)

case "${ARCH}" in
    amd64 | i386) EMULATE=0 ;;
    *) EMULATE=1 ;;
esac

usage() {
    sed -n '5,40p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' >&2
    exit 2
}
die() {
    echo "i386-compat.sh: $*" >&2
    exit 1
}

# i386 package names for this architecture, into I386_PKGS: multiarch
# PKG:i386 everywhere except on an i386 image, where they're native.
i386_packages() {
    I386_PKGS=()
    local pkg
    for pkg in "$@"; do
        if [[ "${ARCH}" == "i386" ]]; then
            I386_PKGS+=("${pkg}")
        else
            I386_PKGS+=("${pkg}:i386")
        fi
    done
}

write_exec() { # write_exec FILE COMMENT EXEC_LINE
    printf '%s\n' '#!/bin/sh' "# Generated by i386-compat.sh: $2" "$3" > "$1"
    chmod 0755 "$1"
}

# Shell fragment (run by /bin/sh at runtime) that starts qemu-i386 with the
# shim preloaded ahead of any LD_PRELOAD the caller set for the guest.
# Sets EXEC_LINE.
qemu_exec() { # qemu_exec QEMU_PATH PROGRAM_EXPR
    # shellcheck disable=SC2016 # ${LD_PRELOAD} and $@ expand at runtime
    printf -v EXEC_LINE 'exec %s -E "LD_PRELOAD=%s${LD_PRELOAD:+:${LD_PRELOAD}}" -E I386_FAKE_CPUINFO=%s %s "$@"' \
        "$1" "${SHIM}" "${FAKE_CPUINFO}" "$2"
}

install_fake_cpuinfo() {
    # SteamCMD (and some engines) exit when /proc/cpuinfo has no x86 flags;
    # under qemu-user it describes the host ARM CPU. The shim redirects
    # opens of /proc/cpuinfo here.
    mkdir -p "${FAKE_CPUINFO%/*}"
    printf '%s\n' \
        'processor	: 0' \
        'vendor_id	: GenuineIntel' \
        'cpu family	: 6' \
        'model		: 85' \
        'model name	: Intel(R) Xeon(R) CPU (qemu-i386)' \
        'cpu MHz		: 3000.000' \
        'cache size	: 16384 KB' \
        'flags		: fpu vme de pse tsc msr pae mce cx8 apic sep mtrr pge mca cmov pat pse36 clflush mmx fxsr sse sse2 ht syscall nx lm constant_tsc pni ssse3 cx16 sse4_1 sse4_2 popcnt' \
        'bogomips	: 6000.00' \
        '' > "${FAKE_CPUINFO}"
}

install_emulator() {
    [[ -f "${SHIM_SRC}" ]] || die "shim source not found: ${SHIM_SRC} (set I386_SHIM_SRC)"
    # qemu-user ships every target (~460 MB); keep only the ~14 MB static
    # i386 emulator and purge the rest, along with the cross compiler.
    local build_deps=(qemu-user gcc-i686-linux-gnu libc6-dev-i386-cross)
    apt-get install -y --no-install-recommends "${build_deps[@]}"
    local src
    for src in /usr/bin/qemu-i386 /usr/bin/qemu-i386-static; do
        if [[ -x "${src}" ]]; then
            install -m 0755 "${src}" "${QEMU}"
            break
        fi
    done
    [[ -x "${QEMU}" ]] || die "qemu-user did not provide qemu-i386"
    i686-linux-gnu-gcc -O2 -shared -fPIC -Wall -Wextra -Werror \
        -o "${SHIM}" "${SHIM_SRC}" -ldl
    apt-get purge -y --auto-remove "${build_deps[@]}"
    install_fake_cpuinfo
    "${QEMU}" --version | head -n 1
}

install_runner() {
    if [[ "${EMULATE}" == "0" ]]; then
        write_exec "${BIN_DIR}/run-i386" "i386 runs natively here." 'exec "$@"'
        return
    fi
    # qemu-user does not search PATH for the guest program, so do it here.
    local lookup
    # shellcheck disable=SC2016 # expanded by /bin/sh at runtime
    lookup='[ "$#" -gt 0 ] || { echo "usage: run-i386 PROGRAM [ARGS...]" >&2; exit 2; }
prog=$1
shift
case "${prog}" in
    */*) ;;
    *) prog=$(command -v "${prog}") || { echo "run-i386: ${prog}: not found" >&2; exit 127; } ;;
esac'
    # shellcheck disable=SC2016
    qemu_exec "${QEMU}" '"${prog}"'
    write_exec "${BIN_DIR}/run-i386" "run an i386 program under qemu-i386." \
        "${lookup}
${EXEC_LINE}"
}

install_launcher() { # install_launcher NAME=PATH
    local name="${1%%=*}" target="${1#*=}"
    [[ "$1" == *=* && -n "${name}" && "${name}" != */* ]] || die "--launcher wants NAME=/path/to/binary, got '$1'"
    [[ "${target}" == /* ]] || die "--launcher ${name}: path must be absolute, got '${target}'"
    if [[ "${EMULATE}" == "0" ]]; then
        write_exec "${BIN_DIR}/${name}" "run ${target} (native i386)." "exec ${target} \"\$@\""
    else
        mkdir -p "${KIT_DIR}/emu"
        ln -sf "${QEMU}" "${KIT_DIR}/emu/${name}"
        qemu_exec "${KIT_DIR}/emu/${name}" "${target}"
        write_exec "${BIN_DIR}/${name}" "run ${target} under qemu-i386 (comm: ${name})." "${EXEC_LINE}"
    fi
    echo "launcher: ${BIN_DIR}/${name} -> ${target}"
}

do_install() {
    local extra_i386=() launchers=() native=() keep_lists=0
    # shellcheck disable=SC2206 # deliberate word splitting of a package list
    extra_i386=(${I386_EXTRA_PACKAGES:-})
    while [[ "$#" -gt 0 ]]; do
        case "$1" in
            --i386-pkg)
                [[ "$#" -ge 2 ]] || die "--i386-pkg needs a package name"
                extra_i386+=("$2")
                shift 2
                ;;
            --launcher)
                [[ "$#" -ge 2 ]] || die "--launcher needs NAME=/path"
                launchers+=("$2")
                shift 2
                ;;
            --keep-apt-lists)
                keep_lists=1
                shift
                ;;
            --)
                shift
                native+=("$@")
                break
                ;;
            -*) die "unknown option: $1" ;;
            *)
                native+=("$1")
                shift
                ;;
        esac
    done

    i386_packages "${BASE_LIBS[@]}" "${extra_i386[@]}"
    if [[ "${ARCH}" != "i386" ]]; then
        dpkg --add-architecture i386
    fi
    apt-get update
    # ca-certificates: without it steamclient can't reach Steam
    # ("disconnected from Steam3"), and most download steps need it anyway.
    apt-get install -y --no-install-recommends ca-certificates "${native[@]}" "${I386_PKGS[@]}"
    if [[ "${EMULATE}" == "1" ]]; then
        install_emulator
    fi
    install_runner
    local l
    for l in "${launchers[@]}"; do
        install_launcher "${l}"
    done
    if [[ "${keep_lists}" == "0" ]]; then
        rm -rf /var/lib/apt/lists/*
    fi
}

cmd="${1:-}"
if [[ "$#" -gt 0 ]]; then
    shift
fi
case "${cmd}" in
    install) do_install "$@" ;;
    packages)
        i386_packages "${BASE_LIBS[@]}"
        echo "${I386_PKGS[*]}"
        ;;
    emulated) [[ "${EMULATE}" == "1" ]] ;;
    *) usage ;;
esac
